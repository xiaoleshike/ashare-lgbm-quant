OPTIONAL_DATASETS: tuple[str, ...] = tuple(
    name for name in DATASET_SPECS if name not in DEFAULT_DATASETS
)
for _dataset_name in OPTIONAL_DATASETS:
    DATASET_SPECS[_dataset_name] = replace(DATASET_SPECS[_dataset_name], optional=True)

ALL_DATASETS: tuple[str, ...] = tuple(DATASET_SPECS)


def get_dataset_spec(name: str) -> DatasetSpec:
    """Return metadata for a configured dataset name."""

    try:
        return DATASET_SPECS[name]
    except KeyError as error:
        known = ", ".join(sorted(DATASET_SPECS))
        raise ValueError(f"Unknown dataset '{name}'. Known datasets: {known}") from error
