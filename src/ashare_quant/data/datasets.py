@dataclass(frozen=True)
class DatasetSpec:
    """Describe one canonical raw Tushare dataset."""

    name: str
    endpoint: str
    kind: DatasetKind
    primary_key: tuple[str, ...]
    required_columns: tuple[str, ...]
    partitioning: Partitioning
    fetch_mode: FetchMode = "snapshot"
    date_column: str | None = None
    uses_trade_calendar: bool = False
    allow_empty_trading_days: bool = False
    revision_lookback_open_days: int = 0
    fields: tuple[str, ...] = ()
    params: dict[str, object] = field(default_factory=dict)
    vip_endpoint: str | None = None
    response_row_limit: int | None = None
    optional: bool = False


